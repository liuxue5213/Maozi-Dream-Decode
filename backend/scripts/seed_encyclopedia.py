def seed():
    """幂等导入：存在则更新，不存在则插入"""
    db = SessionLocal()
    try:
        inserted = 0
        updated = 0
        
        for item_data in ITEMS:
            existing = db.query(EncyclopediaItem).filter(
                EncyclopediaItem.title == item_data["title"]
            ).first()
            
            if existing:
                for key, value in item_data.items():
                    setattr(existing, key, value)
                existing.status = 1
                updated += 1
            else:
                item = EncyclopediaItem(**item_data, status=1)
                db.add(item)
                inserted += 1
        
        db.commit()
        print(f"导入完成：新增 {inserted} 条，更新 {updated} 条，共 {len(ITEMS)} 条")
    except Exception as e:
        db.rollback()
        print(f"导入失败: {e}")
    finally:
        db.close()


if __name__ == "__main__":
    seed()
